const flat = (t) => t.replace(/\s+/g, ' ').trim();
// The mock joins the template on $1..$n, so the value of the placeholder right after `re` is values[n-1].
const boundAfter = (stmt, re) => {
  const m = stmt.text.match(re);
  expect(m, `SQL does not match ${re}`).toBeTruthy();
  const p = stmt.text.slice(m.index + m[0].length).match(/^\$(\d+)/);
  expect(p, `${re} must sit immediately before a binding`).toBeTruthy();
  return stmt.values[Number(p[1]) - 1];
};

