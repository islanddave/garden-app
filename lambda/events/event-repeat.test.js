// BUG-EVENTSREPEATTAP-001 — POST /api/events does not write the same event twice.
//
// THE DEFECT. Prod carries watering pairs 0.2-2.8 s apart, a harvest written three times 21 s and
// 25 s apart, Red Raspberries 0.15 cup twice at 25 s (both live: a doubled season total). api.js
// stops waiting at 15 s, the form is still filled in, and Save works again.
//
// WHAT THIS FILE CAN AND CANNOT PROVE. These drive the REAL handler (Lambda runtime stubs, per-file
// neon mock as in loss-token-alias.test.js) and assert what is SENT and BOUND. The mock runs no SQL,
// so nothing here shows that a repeat writes no row, that a different note still writes one, or that
// the lock serialises two requests — those are the BUG-EVENTSREPEATTAP-001 cases in
// tests/integration/events.int.test.js, on a real Postgres. What IS provable here:
//   - the advisory lock is statement 1 of the write transaction, keyed on the event, gated off for photo;
//   - the repeat check carries the window and compares every written field with what is bound;
//   - the INSERT writes only when the check found nothing, under an id generated by the handler;
//   - the three statements that are not idempotent on a repeat are gated on that id;
//   - a repeat answers 200 with the standing row and runs nothing after the transaction;
//   - a write still answers 201 exactly as before.
