async function post(body) {
  rec.sent = [];
  rec.tx = 0;
  rec.respond = ({ text }) => {
    if (/FROM public\.plants gn\s+LEFT JOIN public\.plant_projects pp/.test(text)) {
      return [{ id: PLANTING, name: 'Red Raspberries', project_id: CONTAINER }];
    }
    if (/SELECT id, name FROM public\.plant_projects/.test(text)) return [{ id: body.project_id, name: 'Bed' }];
    if (/SELECT id, name FROM locations/.test(text)) return [{ id: LOCATION, name: 'Back' }];
    if (/SELECT id, name FROM inventory_items/.test(text)) return [{ id: PRODUCT, name: 'Neem' }];
    if (/SELECT quantity::int AS qty/.test(text)) return [{ qty: 8, harvested: 0, lost: 0, given_away: 0 }];
    if (/AS tz/.test(text)) return [{ tz: 'America/New_York' }];
    if (/WITH dup AS/.test(text)) return [writeRow];
    if (/INSERT INTO user_stats/.test(text)) return [{ current_streak: 3, total_events: 40, level: 2 }];
    if (/WITH today_xp AS/.test(text)) return [{ granted: 10, today_total: 10, level_after_flat: 2 }];
    return [];
  };
  const res = await handler({
    requestContext: { http: { method: 'POST' } },
    rawPath: '/api/events',
    headers: { authorization: 'Bearer stub-token' },
    body: JSON.stringify(body),
  });
  const tx = rec.sent.filter((s) => s.tx === 1);
  const afterTx = rec.sent.slice(rec.sent.findIndex((s) => s.tx === 1) + tx.length);
  return { status: res.statusCode, body: JSON.parse(res.body || '{}'), tx, afterTx };
}

