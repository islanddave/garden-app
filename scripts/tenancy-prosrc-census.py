#!/usr/bin/env python3
"""The prosrc census: every INSERT inside a public or gv function body (V5-SPACETENANCYKEY-001, multi-space plan V204
step 2.2, §2.4 "Writers", DSA-21, MF1).

WHY THIS EXISTS
---------------
Lambda INSERTs are proven by the SQL census (tests/lib/sqlCensus.mjs) and the writer test
(lambda/tenancy-insert.static.test.js). Database functions and triggers write rows too, and CI has no database to
read them from, so this script reads them once, read-only, and commits what it found: tests/tenancy-prosrc.prod.json.
lambda/tenancy-prosrc.static.test.js then holds that file against lambda/tenancy-classes.json and the decisions in
tests/tenancy-prosrc-decisions.json: every function INSERT into an S table or into entity has a decision (stamps from
its parent row; rewritten by a named migration; or allowlisted with the lane that clears it). An INSERT into an S
table that does not name workspace_id relies on the column DEFAULT (the original Space); 5.7's G2 precondition is
that the census shows none.

WHAT IT RECORDS
---------------
Every function in schemas public and gv written in sql or plpgsql: its identity signature, language, md5(prosrc) and
the triggers that call it; for a body that holds an INSERT, each INSERT's target, column list and the value bound to
workspace_id (tests/lib/prosrcCensus.mjs does the parsing, with the same PostgreSQL 17 grammar as the SQL census), and
the body itself so the static test can re-run the analysis. Only definitions: no rows, no data.

RE-RUNNING (read-only; the URL comes from the environment by key name, never the command line, L-067):
  NEON_DATABASE_URL=... python3 scripts/tenancy-prosrc-census.py                  # rewrites tests/tenancy-prosrc.prod.json
  NEON_STAGING_URL=...  python3 scripts/tenancy-prosrc-census.py --env staging --check
      # exit 1 and print the differences if staging's functions differ from the committed prod census
  python3 scripts/tenancy-prosrc-census.py --bodies dump.json --check            # offline: a saved catalog read
Re-run after any migration that creates or replaces a public/gv function, commit prod's output, then run
`npx vitest run lambda/tenancy-prosrc.static.test.js`: it names every INSERT that lacks a decision.
The connection is opened read_only (PostgreSQL refuses any write) and the transaction is rolled back.
"""
import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CENSUS = ROOT / "tests" / "tenancy-prosrc.prod.json"
ANALYZER = ROOT / "tests" / "lib" / "prosrcCensus.mjs"

QUERY = """
SELECT n.nspname::text, p.proname::text, pg_get_function_identity_arguments(p.oid), l.lanname::text,
       md5(p.prosrc), p.prosrc,
       coalesce((SELECT array_agg(t.relname::text || ':' || g.tgname::text ORDER BY t.relname, g.tgname)
                   FROM pg_trigger g JOIN pg_class t ON t.oid = g.tgrelid
                  WHERE g.tgfoid = p.oid AND NOT g.tgisinternal), '{}')
  FROM pg_proc p
  JOIN pg_namespace n ON n.oid = p.pronamespace
  JOIN pg_language l ON l.oid = p.prolang
 WHERE n.nspname IN ('public', 'gv')
   AND l.lanname IN ('sql', 'plpgsql')
 ORDER BY 1, 2, 3
"""


def read_functions(env):
    var = "NEON_DATABASE_URL" if env == "prod" else "NEON_STAGING_URL"
    url = os.environ.get(var)
    if not url:
        raise SystemExit(f"FATAL: {var} is not set (needed for --env {env}). Never pass a URL on the command line.")
    import psycopg  # after the URL check: CI's pytest leg has no psycopg

    with psycopg.connect(url) as conn:
        conn.read_only = True
        with conn.cursor() as cur:
            # The pooler hands over other clients' session state (OPS-GATEINVARIANTSFLAKE-001).
            cur.execute("SET LOCAL search_path TO DEFAULT")
            cur.execute(QUERY, prepare=False)
            rows = cur.fetchall()
        conn.rollback()
    return [
        {"schema": s, "name": n, "args": a, "lang": lang, "md5": h, "src": src, "triggers": list(trg)}
        for s, n, a, lang, h, src, trg in rows
    ]


def analyse(functions, env):
    payload = json.dumps({"functions": functions, "meta": {"env": env}})
    out = subprocess.run(
        ["node", str(ANALYZER), "--analyze", "/dev/stdin"], input=payload, capture_output=True, text=True, cwd=ROOT
    )
    if out.returncode != 0:
        raise SystemExit(f"FATAL: {ANALYZER.relative_to(ROOT)} failed:\n{out.stderr}")
    return json.loads(out.stdout)


def render(census):
    head = [
        "Generated by scripts/tenancy-prosrc-census.py from a read-only read of the " + census["env"]
        + " catalog (pg_proc, schemas public and gv, languages sql and plpgsql). Do not hand-edit: re-run it.",
        "Read by lambda/tenancy-prosrc.static.test.js against lambda/tenancy-classes.json and "
        "tests/tenancy-prosrc-decisions.json. workspace.named false on an S-table or entity INSERT = DEFAULT-reliant.",
    ]
    lines = ["{", '  "_doc": [\n' + ",\n".join("    " + json.dumps(s) for s in head) + "\n  ],"]
    lines.append(f'  "env": {json.dumps(census["env"])},')
    lines.append('  "functions": [')
    lines.append(",\n".join("    " + json.dumps(f) for f in census["functions"]))
    lines.append("  ]")
    lines.append("}")
    return "\n".join(lines) + "\n"


def diff(want, have):
    w = {f["function"]: f for f in want["functions"]}
    h = {f["function"]: f for f in have["functions"]}
    out = []
    for k in sorted(set(w) | set(h)):
        if k not in h:
            out.append(f"only in the committed census: {k}")
        elif k not in w:
            out.append(f"only in the database: {k}")
        elif w[k]["md5"] != h[k]["md5"]:
            out.append(f"body differs: {k}: census md5 {w[k]['md5']}, database {h[k]['md5']}")
        elif w[k].get("triggers") != h[k].get("triggers"):
            out.append(f"triggers differ: {k}: census {w[k].get('triggers')}, database {h[k].get('triggers')}")
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--env", choices=("prod", "staging"), default="prod")
    ap.add_argument("--check", action="store_true", help="compare with the committed census instead of writing it")
    ap.add_argument("--bodies", help="read the functions from a saved JSON list instead of the database")
    args = ap.parse_args()
    functions = json.loads(Path(args.bodies).read_text()) if args.bodies else read_functions(args.env)
    census = analyse(functions, args.env)
    with_insert = [f for f in census["functions"] if f.get("inserts")]
    summary = f"{args.env}: {len(census['functions'])} functions, {len(with_insert)} with an INSERT"
    if args.check:
        problems = diff(json.loads(CENSUS.read_text()), census)
        for p in problems:
            print(p)
        print(f"{summary}, {len(problems)} difference(s) from {CENSUS.relative_to(ROOT)}")
        return 1 if problems else 0
    if args.env != "prod":
        raise SystemExit("FATAL: the committed census is prod's; use --check for staging.")
    CENSUS.write_text(render(census))
    print(f"wrote {CENSUS.relative_to(ROOT)}: {summary}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
