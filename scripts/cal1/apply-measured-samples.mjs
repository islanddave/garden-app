#!/usr/bin/env node
// apply-measured-samples.mjs — derive per-(variety, unit) grams from the RAW measured samples in
// src/data/harvest-weights-v2.json and emit the SQL that promotes them into
// plant_varieties.unit_weights with weight_source='measured'.
//
//   node scripts/cal1/apply-measured-samples.mjs > /tmp/measured.sql
//   psql "$NEON_DATABASE_URL" -v ON_ERROR_STOP=1 -f /tmp/measured.sql
//   psql "$NEON_DATABASE_URL" -v ON_ERROR_STOP=1 -f migrations/v4-cal1-refweight-001/0d-backfill.sql
//
// This is the "as I weigh things" loop: append samples to v2.json, run this, re-run the backfill.
//
// DERIVATION — count-weighted pooled ratio, matching src/lib/cal1Weights.js and the
// cultivar_weight_derived view specced in v4-cal1-pervariety-001:
//     grams_per_unit = SUM(total_grams) / SUM(unit_count)   over non-voided samples
// Weighting by unit_count (not averaging per-sample ratios) is what makes "12 fruit @ 74 g total"
// count 12× as much as "1 fruit @ 115 g" — the raw numerator/denominator are preserved in v2.json
// precisely so this stays auditable and re-derivable.
//
// SCOPE NOTE — this writes a per-unit value into a row-level weight_source. The emitted UPDATE
// therefore REPLACES unit_weights with a measured-only map rather than merging into the estimated
// one: keeping an unmeasured 'cup' key alongside weight_source='measured' would overclaim it. Units
// with no sample correctly fall back to the crop tier. Per-unit provenance arrives with
// v4-cal1-pervariety-001, whose samples are keyed on (cultivar, unit).

import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = resolve(HERE, '../../src/data/harvest-weights-v2.json');
const UNITS = new Set(['lb', 'oz', 'kg', 'g', 'count', 'bunch', 'cup', 'head']);

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

// Exported for src/__tests__/cal1MeasuredSamples.test.js. This is the arithmetic behind every
// measured yield number, so it is unit-tested rather than trusted. NUL is the key separator because
// variety names contain spaces ('San Marzano Roma') but can never contain a NUL.
export function poolSamples(doc) {
  // voids are matched on the same tuple the corrections_note specifies; a voided sample is excluded
  const voided = new Set(
  (doc.by_cultivar_voids ?? []).map((v) =>
    [v.crop_type_slug, v.variety_name, v.sampled_at, v.total_grams].join('\0')),
  );

  const pooled = new Map(); // "crop\0variety\0unit" -> {grams, count, n}
  for (const s of doc.by_cultivar_samples ?? []) {
  if (String(s.variety_name ?? '').startsWith('__TEMPLATE__')) continue;
  if (!(s.total_grams > 0) || !(s.unit_count > 0)) continue;
  if (!UNITS.has(s.unit)) throw new Error(`sample ${s.variety_name}: unit '${s.unit}' outside vocabulary`);
  if (voided.has([s.crop_type_slug, s.variety_name, s.sampled_at, s.total_grams].join('\0'))) continue;
  const k = [s.crop_type_slug, s.variety_name, s.unit].join('\0');
  const cur = pooled.get(k) ?? { grams: 0, count: 0, n: 0 };
  cur.grams += s.total_grams; cur.count += s.unit_count; cur.n += 1;
  pooled.set(k, cur);
}

// regroup to one row per (crop, variety) carrying every measured unit
  const byVariety = new Map();
for (const [k, v] of pooled) {
  const [crop, variety, unit] = k.split('\0');
  const vk = `${crop}\0${variety}`;
  const cur = byVariety.get(vk) ?? { crop, variety, units: {}, n: 0 };
  cur.units[unit] = Number((v.grams / v.count).toFixed(3));
  cur.n += v.n;
  byVariety.set(vk, cur);
}

  return [...byVariety.values()].sort((a, b) =>
    a.crop.localeCompare(b.crop) || a.variety.localeCompare(b.variety));
}

export function generateSQL(rows) {
  const out = [];
  out.push('-- GENERATED by scripts/cal1/apply-measured-samples.mjs. DO NOT EDIT BY HAND.');
  out.push(`-- Source: src/data/harvest-weights-v2.json (${rows.length} varieties, count-weighted pooled ratio)`);
  out.push('-- Promotes MEASURED samples into plant_varieties.unit_weights. Run the refweight');
  out.push('-- 0d-backfill.sql afterwards to re-derive harvest_log.weight_grams from the new factors.');
  out.push('');
  out.push('BEGIN;');
  for (const r of rows) {
  const js = JSON.stringify(r.units);
  out.push(`-- ${r.crop}/${r.variety} — ${r.n} sample(s)`);
  out.push(`UPDATE public.plant_varieties SET unit_weights=${q(js)}::jsonb, weight_source='measured', weight_confidence='high', updated_at=now()`);
  out.push(` WHERE crop_type_slug=${q(r.crop)} AND name=${q(r.variety)} AND deleted_at IS NULL;`);
}
out.push('COMMIT;');
  return out.join('\n') + '\n';
}

// CLI entry only — guarded so the test file can import poolSamples/generateSQL without the
// module emitting a full SQL script to stdout on import.
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const doc = JSON.parse(readFileSync(SRC, 'utf8'));
  process.stdout.write(generateSQL(poolSamples(doc)));
}
