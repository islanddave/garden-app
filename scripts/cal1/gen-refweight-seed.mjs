#!/usr/bin/env node
// gen-refweight-seed.mjs — emit migrations/v4-cal1-refweight-001/0b-seed.sql from
// src/data/harvest-weights-v3-reference.json (the authoring source of record for the ESTIMATE tier).
//
// Pure transform: no DB access at generate time. Run:
//   node scripts/cal1/gen-refweight-seed.mjs > migrations/v4-cal1-refweight-001/0b-seed.sql
//
// Emitted SQL properties:
//   * MEASURED-SAFE — every UPDATE carries `AND (weight_source IS NULL OR weight_source <> 'measured')`,
//     so re-running can never clobber a value that came from a real weighing.
//   * IDEMPOTENT — plain UPDATEs keyed on natural keys (crop_types.slug / plant_varieties
//     (crop_type_slug, name)); re-applying converges to the same state.
//   * NON-DESTRUCTIVE ON MISS — a key with no live row updates 0 rows. Unlike the measured-sample
//     seeder this does NOT need fail-closed single-match resolution: a duplicate (crop, name) pair
//     legitimately receives the SAME reference estimate on every matching row, so >1 match is correct
//     behaviour, not ambiguity. 0d-coverage.sql reports what actually landed.

import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = resolve(HERE, '../../src/data/harvest-weights-v3-reference.json');
const UNITS = new Set(['lb', 'oz', 'kg', 'g', 'count', 'bunch', 'cup', 'head']);

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

function validateWeights(w, where) {
  if (w == null || typeof w !== 'object' || Array.isArray(w)) throw new Error(`${where}: unit_weights must be an object`);
  const keys = Object.keys(w);
  if (!keys.length) throw new Error(`${where}: unit_weights is empty`);
  for (const k of keys) {
    if (!UNITS.has(k)) throw new Error(`${where}: unit '${k}' is outside the harvest unit vocabulary`);
    const v = w[k];
    if (typeof v !== 'number' || !Number.isFinite(v) || v <= 0) throw new Error(`${where}: ${k}=${v} must be a positive finite number`);
  }
  return JSON.stringify(w);
}

const doc = JSON.parse(readFileSync(SRC, 'utf8'));
const out = [];
const P = (s) => out.push(s);

P('-- 0b-seed.sql — GENERATED by scripts/cal1/gen-refweight-seed.mjs. DO NOT EDIT BY HAND.');
P(`-- Source: src/data/harvest-weights-v3-reference.json (schema ${doc.schema_version}, authored ${doc.authored})`);
P('--');
P('-- Seeds the REFERENCE (estimate) tier only. Never writes weight_source=\'measured\', and every');
P('-- statement refuses to overwrite a row already marked measured. Idempotent; re-runnable.');
P('-- Apply AFTER 0a. Take the CTAS snapshots named in 0a before running this.');
P('');
P('BEGIN;');
P('');
P(`-- ${Object.keys(doc.by_crop_type).length} crop types (fallback tier) ------------------------------------`);

for (const [slug, r] of Object.entries(doc.by_crop_type).sort(([a], [b]) => a.localeCompare(b))) {
  const w = validateWeights(r.unit_weights, `crop_types.${slug}`);
  if (!UNITS.has(r.primary_unit)) throw new Error(`crop_types.${slug}: bad primary_unit ${r.primary_unit}`);
  if (r.unit_weights[r.primary_unit] !== r.grams_per_unit) throw new Error(`crop_types.${slug}: grams_per_unit out of sync with unit_weights[${r.primary_unit}]`);
  P(`UPDATE public.crop_types SET unit_weights=${q(w)}::jsonb, weight_source=${q(r.source)}, weight_confidence=${q(r.confidence)},`);
  // keep the harvweight-001 scalar pair in sync so the already-specced Lambda derivation keeps working
  P(`       default_unit=COALESCE(default_unit,${q(r.primary_unit)}), grams_per_unit=(${q(w)}::jsonb->>COALESCE(default_unit,${q(r.primary_unit)}))::numeric, updated_at=now()`);
  P(` WHERE slug=${q(slug)} AND deleted_at IS NULL AND (weight_source IS NULL OR weight_source <> 'measured');`);
}

P('');
P(`-- ${doc.by_variety.length} varieties (override tier; wins over the crop fallback) ----------------`);
for (const r of doc.by_variety) {
  const w = validateWeights(r.unit_weights, `variety ${r.crop_type_slug}/${r.variety_name}`);
  P(`UPDATE public.plant_varieties SET unit_weights=${q(w)}::jsonb, weight_source=${q(r.source)}, weight_confidence=${q(r.confidence)}, updated_at=now()`);
  P(` WHERE crop_type_slug=${q(r.crop_type_slug)} AND name=${q(r.variety_name)} AND deleted_at IS NULL`);
  P(`   AND (weight_source IS NULL OR weight_source <> 'measured');`);
}

P('');
P("INSERT INTO public.schema_version (version, description)");
P(`VALUES ('4.18.1-cal1-refweight-seed-001','CAL-1 reference seed: unit_weights/weight_source/weight_confidence for ${Object.keys(doc.by_crop_type).length} crop types + ${doc.by_variety.length} varieties from harvest-weights-v3-reference.json. Estimates only; measured rows are never overwritten.')`);
P('ON CONFLICT (version) DO NOTHING;');
P('');
P('COMMIT;');

process.stdout.write(out.join('\n') + '\n');
