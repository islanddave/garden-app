#!/usr/bin/env python3
"""Catalog snapshot for the tenancy class file (V5-SPACETENANCYKEY-001, multi-space plan V204 step 2.0b, §2.1).

WHY THIS EXISTS
---------------
lambda/tenancy-classes.json names every relation's class and tenancy column, and says whether that column is
NOT NULL. lambda/tenancy-classes.test.js checks each row against the catalog, but CI has no database, so the test
reads this script's output instead: tests/tenancy-catalog.prod.json, a committed read of prod's catalog. When a
migration adds a relation or changes a tenancy column, regenerate the snapshot in the same commit as the class
file edit; the test then says which rows disagree.

WHAT IT RECORDS
---------------
Every relation of relkind r, p, v, m, f in every non-system schema, minus the copy tables (the anchored regexes
in the class file's copyPatterns), keyed schema.relname: its relkind, and for each column the class file names
anywhere (plus workspace_id, space_id, is_base) that the relation has: attnotnull and the target of a
single-column foreign key on it, if any. Only names and booleans: no rows, no data.

REGENERATING (read-only; the URL comes from the environment by key name, never the command line, L-067):
  NEON_DATABASE_URL=... python3 scripts/tenancy-catalog-snapshot.py            # rewrites tests/tenancy-catalog.prod.json
  NEON_STAGING_URL=...  python3 scripts/tenancy-catalog-snapshot.py --env staging --check
      # exit 1 and print the differences if staging's catalog differs from the committed prod snapshot
The connection is opened read_only (PostgreSQL refuses any write) and the transaction is rolled back.
"""
import argparse
import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CLASSES = ROOT / "lambda" / "tenancy-classes.json"
SNAPSHOT = ROOT / "tests" / "tenancy-catalog.prod.json"
ALWAYS = ("workspace_id", "space_id", "is_base")

QUERY = """
SELECT n.nspname::text, c.relname::text, c.relkind::text,
       coalesce((SELECT json_agg(json_build_array(a.attname::text, a.attnotnull, (
                   SELECT tn.nspname || '.' || t.relname
                     FROM pg_constraint con
                     JOIN pg_class t ON t.oid = con.confrelid
                     JOIN pg_namespace tn ON tn.oid = t.relnamespace
                    WHERE con.conrelid = c.oid AND con.contype = 'f' AND con.conkey = ARRAY[a.attnum]
                    ORDER BY con.conname LIMIT 1)) ORDER BY a.attnum)
                   FROM pg_attribute a
                  WHERE a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped), '[]'::json)
  FROM pg_class c
  JOIN pg_namespace n ON n.oid = c.relnamespace
 WHERE c.relkind IN ('r', 'p', 'v', 'm', 'f')
   AND n.nspname NOT IN ('pg_catalog', 'information_schema')
   AND n.nspname !~ '^pg_(toast|temp_)'
 ORDER BY 1, 2
"""


def wanted_columns(classes):
    names = set(ALWAYS)
    for row in classes["relations"].values():
        if row.get("column"):
            names.add(row["column"])
        names.update(row.get("alsoVia", {}))
    return names


def read_catalog(env, classes):
    import psycopg

    var = "NEON_DATABASE_URL" if env == "prod" else "NEON_STAGING_URL"
    url = os.environ.get(var)
    if not url:
        raise SystemExit(f"FATAL: {var} is not set (needed for --env {env}). Never pass a URL on the command line.")
    copies = [re.compile(p) for p in classes["copyPatterns"]]
    cols = wanted_columns(classes)
    with psycopg.connect(url) as conn:
        conn.read_only = True
        with conn.cursor() as cur:
            # The pooler hands over other clients' session state (OPS-GATEINVARIANTSFLAKE-001).
            cur.execute("SET LOCAL search_path TO DEFAULT")
            cur.execute(QUERY, prepare=False)
            rows = cur.fetchall()
        conn.rollback()
    rels = {}
    for nsp, rel, kind, attrs in rows:
        if any(p.search(rel) for p in copies):
            continue
        rels[f"{nsp}.{rel}"] = {
            "kind": kind,
            "columns": {a: {"notnull": nn, "fk": fk} for a, nn, fk in attrs if a in cols},
        }
    return rels


def render(env, rels):
    head = {
        "_doc": [
            "Generated by scripts/tenancy-catalog-snapshot.py from a read-only read of the " + env + " catalog. Do not hand-edit.",
            "Read by lambda/tenancy-classes.test.js (the attnotnull sync test). Regenerate with the class file edit.",
        ],
        "env": env,
    }
    lines = ["{"]
    lines.append('  "_doc": [\n' + ",\n".join("    " + json.dumps(s) for s in head["_doc"]) + "\n  ],")
    lines.append(f'  "env": {json.dumps(env)},')
    lines.append('  "relations": {')
    lines.append(",\n".join(f"    {json.dumps(k)}: {json.dumps(rels[k])}" for k in sorted(rels)))
    lines.append("  }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def diff(want, have):
    out = []
    for k in sorted(set(want) | set(have)):
        if k not in have:
            out.append(f"only in the snapshot: {k}")
        elif k not in want:
            out.append(f"only in the database: {k}")
        elif want[k] != have[k]:
            out.append(f"differs: {k}: snapshot {json.dumps(want[k])} database {json.dumps(have[k])}")
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--env", choices=("prod", "staging"), default="prod")
    ap.add_argument("--check", action="store_true", help="compare with the committed snapshot instead of writing it")
    args = ap.parse_args()
    classes = json.loads(CLASSES.read_text())
    rels = read_catalog(args.env, classes)
    if args.check:
        problems = diff(json.loads(SNAPSHOT.read_text())["relations"], rels)
        for p in problems:
            print(p)
        print(f"{args.env}: {len(rels)} relations, {len(problems)} difference(s) from {SNAPSHOT.relative_to(ROOT)}")
        return 1 if problems else 0
    if args.env != "prod":
        raise SystemExit("FATAL: the committed snapshot is prod's; use --check for staging.")
    SNAPSHOT.write_text(render(args.env, rels))
    print(f"wrote {SNAPSHOT.relative_to(ROOT)}: {len(rels)} relations")
    return 0


if __name__ == "__main__":
    sys.exit(main())
