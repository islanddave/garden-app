#!/usr/bin/env python3
"""Tests for the Phase 7 gate (multi-space plan V204 §4, step 2.0f; V5-SPACEISOLATION-001).

The map test proper: scripts/phase7-gate.json's step map is closed-world against scripts/multispace-steps.json
(generated from the plan by project-state/_multispace-20261015/tools/steps_from_plan.py). It fails on an
unmapped step, a map key that is not a step, a step claimed twice, or a missing item. Plus phase7-gate.py's
fixture-mode rules: an empty fixture is NO_EVIDENCE, never PASS, and --self-test's failing fixtures FAIL.

Run on a plan's §4 prose instead of the JSON map (the V203 positive control: 3.3b claimed twice):
  python3 scripts/test_phase7_gate_map.py --plan <multispace-prep-plan-V203-....md>
"""
import copy
import importlib.util
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
CONFIG = os.path.join(HERE, "phase7-gate.json")
STEPS = os.path.join(HERE, "multispace-steps.json")


def _load_gate():
    spec = importlib.util.spec_from_file_location("phase7_gate", os.path.join(HERE, "phase7-gate.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


pg = _load_gate()


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def real():
    cfg, dups = pg.load_map_text(read(CONFIG))
    return cfg, dups, json.loads(read(STEPS))


def errors_for(cfg, steps_doc, dups=()):
    return pg.map_errors(cfg, steps_doc, list(dups), REPO)


# --- the committed map ---------------------------------------------------------------------------------------
def test_committed_map_is_closed_world():
    cfg, dups, steps_doc = real()
    assert errors_for(cfg, steps_doc, dups) == []


def test_steps_file_is_generated_and_unique():
    steps_doc = json.loads(read(STEPS))
    assert "GENERATED by" in steps_doc["_doc"] and "steps_from_plan.py" in steps_doc["_doc"]
    ids = [s["id"] for s in steps_doc["steps"]]
    assert len(ids) == len(set(ids))
    assert steps_doc["items"] == ["G%d" % n for n in range(1, len(steps_doc["items"]) + 1)]
    for new_id in ("2.0e", "2.0f", "4.0", "6.1b"):
        assert new_id in ids, new_id


def test_exclusions_are_ids_with_reasons():
    cfg, _, _ = real()
    for key, val in cfg["steps"].items():
        assert not pg.RANGE_RE.match(key), key
        if isinstance(val, dict):
            assert list(val) == ["excluded"] and val["excluded"].strip(), key


# --- each failure the map test must catch --------------------------------------------------------------------
def test_unmapped_step_reds():
    cfg, dups, steps_doc = real()
    del cfg["steps"]["4.4"]
    errs = errors_for(cfg, steps_doc, dups)
    assert "unmapped step: 4.4" in errs
    assert "item G14 is claimed by no step" in errs


def test_map_key_that_is_not_a_step_reds():
    cfg, dups, steps_doc = real()
    cfg["steps"]["2.5"] = "G8"
    assert "map key 2.5 is not a step" in errors_for(cfg, steps_doc, dups)


def test_range_key_reds():
    cfg, dups, steps_doc = real()
    cfg["steps"]["3.1-3.5"] = {"excluded": "Dave's plots only"}
    assert "map key 3.1-3.5 is a range: write each id" in errors_for(cfg, steps_doc, dups)


def test_step_claimed_twice_in_the_json_reds():
    text = read(CONFIG).replace('"3.3b": "G6",', '"3.3b": "G6",\n    "3.3b": {"excluded": "Dave\'s plots only"},')
    cfg, dups = pg.load_map_text(text)
    assert dups == ["3.3b"]
    assert "step 3.3b claimed twice (the map lists the key twice)" in errors_for(cfg, json.loads(read(STEPS)), dups)


def test_missing_item_reds():
    cfg, dups, steps_doc = real()
    del cfg["items"]["G9"]
    errs = errors_for(cfg, steps_doc, dups)
    assert "missing item: G9 (the plan's §4 names it)" in errs
    assert "step 5.9 names G9, which is not an item" in errs


def test_list_value_rules():
    cfg, dups, steps_doc = real()
    cfg["steps"]["2.7"] = ["G6", "G6"]
    cfg["steps"]["5.4"] = ["G4", "G99"]
    errs = errors_for(cfg, steps_doc, dups)
    assert "step 2.7: a G list must be non-empty with no repeats" in errs
    assert "step 5.4 names G99, which is not an item" in errs


def test_g1_migration_list_is_closed_world():
    cfg, dups, steps_doc = real()
    g1 = cfg["items"]["G1"]
    del g1["migrations"]["2.1"]
    g1["migrations"]["3.1"] = []
    g1["migrations"]["1.9"] = ["5.1.5-spacefk-001-fodl"]
    errs = errors_for(cfg, steps_doc, dups)
    assert any(e.startswith("G1: step 2.1 reads as a migration") for e in errs)
    assert "G1: step 3.1's plan row names stamp 5.3.6-plottier-001; the list lacks it" in errs
    assert "G1: stamp 5.1.5-spacefk-001-fodl (step 1.9) is written by no migrations/*/*.sql" in errs


# --- the plan-text control (V203 §1R.2: the pre-fix V203 text reds on 3.3b claimed twice) ---------------------
V203_SHAPED = """## 4. Phase 7: the second-owner gate

| Item | Steps | Checks |
|---|---|---|
| G5 Isolation suite | 2.0a, 2.0b, 2.2, 4.3, 5.1-5.3 | named test files |
| G6 Populated second Space | 1.12, 3.3b | C-HARNESS artifact |
| G11 Station and frost | 3.6, 5.4 | explicit binding live |

**Excluded, with reasons (the map test is the authority):** 2.0c, 2.0d (ops tooling), 3.1-3.5, 3.7 (Dave's plots only), 4.1 (G5 through 4.3).

## 5. Decisions
"""


def test_plan_text_with_a_range_over_3_3b_reds():
    errs = pg.plan_text_errors(V203_SHAPED, json.loads(read(STEPS)))
    assert "step 3.3b claimed twice (G6, excluded)" in errs
    # A parenthesised reason claims nothing, and distinct G items may share a step.
    assert not any(e.startswith("step 4.3 claimed twice") for e in errs)


def test_plan_text_with_ids_instead_of_the_range_does_not_double_claim():
    fixed = V203_SHAPED.replace("3.1-3.5, 3.7", "3.1, 3.2a, 3.2b, 3.2c, 3.2d, 3.3a, 3.4, 3.5, 3.7")
    errs = pg.plan_text_errors(fixed, json.loads(read(STEPS)))
    assert not any("claimed twice" in e for e in errs), errs


# --- phase7-gate.py fixture mode -----------------------------------------------------------------------------
def test_self_test_passes_on_the_committed_config():
    failures, lines = pg.self_test(pg.load_config(CONFIG))
    assert failures == [], "\n".join(lines)


def test_self_test_catches_a_check_that_always_passes(monkeypatch):
    monkeypatch.setitem(pg.CHECKS, "fact", lambda c, inp, ctx: (pg.PASS, "always"))
    failures, _ = pg.self_test(pg.load_config(CONFIG))
    assert any("failing fixture" in f for f in failures)
    assert any("without" in f for f in failures)


def test_empty_fixture_is_no_evidence_never_pass(tmp_path):
    cfg = pg.load_config(CONFIG)
    for g in cfg["items"]:
        (tmp_path / (g + ".json")).write_text("{}")
    report = pg.run(cfg, str(tmp_path), "a" * 40)
    assert {r["status"] for r in report} == {pg.NO_EVIDENCE}
    assert pg.main(["--inputs", str(tmp_path), "--sha", "a" * 40]) == 1


def test_no_inputs_at_all_is_no_evidence(tmp_path):
    report = pg.run(pg.load_config(CONFIG), str(tmp_path), "a" * 40)
    assert {r["status"] for r in report} == {pg.NO_EVIDENCE}


def test_unreadable_inputs_fail(tmp_path):
    (tmp_path / "G12.json").write_text("{not json")
    report = {r["item"]: r["status"] for r in pg.run(pg.load_config(CONFIG), str(tmp_path), "a" * 40)}
    assert report["G12"] == pg.FAIL


def test_all_pass_exits_zero(tmp_path):
    cfg = pg.load_config(CONFIG)
    done = {g: pg.complete_item(v) for g, v in cfg["items"].items()}
    path = tmp_path / "cfg.json"
    path.write_text(json.dumps(dict(cfg, items=done)))
    sha = pg.SELF_SHA
    for g, item in done.items():
        (tmp_path / (g + ".json")).write_text(json.dumps(pg.passing_inputs(g, item)))
    assert pg.main(["--config", str(path), "--inputs", str(tmp_path), "--sha", sha]) == 0
    assert pg.main(["--config", str(path), "--inputs", str(tmp_path), "--sha", "b" * 40]) == 1


def test_skipped_g_file_fails_its_item_while_ci_is_green():
    """V204 §4's positive control: a G file wrapped in describe.skipIf(true) FAILs its item while CI stays green."""
    cfg = pg.load_config(CONFIG)
    item = pg.complete_item(cfg["items"]["G5"])
    inp = pg.passing_inputs("G5", item)
    path = "lambda/sql-census.static.test.js"
    text = "describe.skipIf(true)('census', () => {\n" + read(os.path.join(REPO, path)) + "\n})\n"
    scanned = pg.scan_test_text(text)
    assert scanned["banned"]
    rec = inp["tests"]["files"][path]
    rec.update(scanned, passed=0, skipped=rec["static_tests"])
    assert inp["tests"]["ci_conclusion"] == "success"
    status, results = pg.evaluate_item("G5", item, inp, {"G5": inp}, pg.SELF_SHA)
    assert status == pg.FAIL
    assert any(r[0] == "suite-tests" and r[1] == pg.FAIL for r in results)
    # The runtime arm alone: a skip the static ban allows (a non-literal condition) still FAILs on skipped > 0.
    rec["banned"] = []
    status, _ = pg.evaluate_item("G5", item, inp, {"G5": inp}, pg.SELF_SHA)
    assert status == pg.FAIL


def test_named_g_files_meet_their_minimums_at_this_sha():
    cfg = pg.load_config(CONFIG)
    for g, item in cfg["items"].items():
        for c in item["checks"]:
            for f in c.get("files", []):
                p = os.path.join(REPO, f["path"])
                assert os.path.exists(p), (g, f["path"])
                scanned = pg.scan_test_text(read(p))
                assert scanned["banned"] == [], (g, f["path"], scanned["banned"])
                assert scanned["static_tests"] >= f["min_tests"], (g, f["path"], scanned)


def test_equal_check_reads_the_other_item():
    cfg = pg.load_config(CONFIG)
    items = {g: pg.complete_item(v) for g, v in cfg["items"].items()}
    good = {g: pg.passing_inputs(g, v) for g, v in items.items()}
    g6 = copy.deepcopy(good["G6"])
    g6["values"]["seed_sql_md5"] = "0" * 32
    status, results = pg.evaluate_item("G7", items["G7"], good["G7"], dict(good, G6=g6), pg.SELF_SHA)
    assert status == pg.FAIL
    assert any(r[0] == "seed-md5-equals-g6" and r[1] == pg.FAIL for r in results)


if __name__ == "__main__":
    # Manual control: check a plan's §4 prose (python3 scripts/test_phase7_gate_map.py --plan PLAN.md).
    sys.exit(pg.main(["--check-map"] + sys.argv[1:]))
