#!/usr/bin/env node
// ============================================================
// Codegen: lambda/daily-plan/frostClass.js BAND_BY_SLUG  ->  src/lib/frostBands.generated.js
// ============================================================
// End of season screen (lane seasonend-20260929). The page decides "does this crop die at frost?"
// from the frost alert's own band map, read DIRECTLY (tender / chill_sensitive), never through CLASS_BY_BAND or
// TENDER_SLUGS — those fold tropical and light_frost_tolerant into 'tender', and frostClassForSlug
// counts an unknown slug as tender. The cautious answer for an alert is the unsafe answer for
// ending plantings.
//
// The map lives in the daily-plan Lambda, and the client cannot import it: frostClass.js is a
// CommonJS Lambda module that reads process.env at module load. The same boundary the events
// Lambda has in the other direction (scripts/gen-lambda-event-types.mjs), so the same answer: a
// generated, COMMITTED copy. The direction is reversed because the canon is the Lambda here.
//
// Run: `node scripts/gen-frost-bands.mjs` (overwrite) or `--check` (exit 1 on drift).
// src/__tests__/frostBands.parity.test.js runs renderFrostBands() in the unit suite and reds on any
// difference in data OR bytes, so a band edit in frostClass.js cannot ship without regenerating.

import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const __dirname = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(__dirname, '..')
export const FROST_CLASS_PATH = join(repoRoot, 'lambda', 'daily-plan', 'frostClass.js')
export const OUT_PATH = join(repoRoot, 'src', 'lib', 'frostBands.generated.js')

const IDENT = /^[a-z_][a-z0-9_]*$/

// Pure: the file text for a given band map. Entry order is the map's own (BAND_ORDER, then each
// band's slug list as written), so a regenerate after an unrelated edit is byte-identical.
export function renderFrostBands({ BAND_BY_SLUG, BAND_ORDER }) {
  const key = (k) => (IDENT.test(k) ? k : JSON.stringify(k))
  const lines = Object.entries(BAND_BY_SLUG).map(([slug, band]) => `  ${key(slug)}: '${band}',`)
  return `// ============================================================
// AUTO-GENERATED by scripts/gen-frost-bands.mjs — DO NOT EDIT BY HAND.
// ============================================================
// Source of truth: lambda/daily-plan/frostClass.js BAND_BY_SLUG, the frost alert's band map.
// Regenerate: \`node scripts/gen-frost-bands.mjs\`. src/__tests__/frostBands.parity.test.js reds
// on any difference from the source, in data or in bytes.
//
// WHY this file exists: the client cannot import the daily-plan Lambda's CommonJS module (it reads
// process.env at load). Only BAND_BY_SLUG is copied — never CLASS_BY_BAND, TENDER_SLUGS or
// UNKNOWN_BAND. A slug the map does not name has NO band here, deliberately: the alert counts an
// unknown crop as tender, and that cautious default must never reach a surface that ENDS plantings.

export const FROST_BANDS = Object.freeze([${BAND_ORDER.map((b) => `'${b}'`).join(', ')}])

export const FROST_BAND_BY_SLUG = Object.freeze({
${lines.join('\n')}
})
`
}

export function loadFrostClass() {
  return createRequire(import.meta.url)(FROST_CLASS_PATH)
}

const invokedDirectly = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]
if (invokedDirectly) {
  const text = renderFrostBands(loadFrostClass())
  if (process.argv.includes('--check')) {
    const current = readFileSync(OUT_PATH, 'utf8')
    if (current !== text) {
      console.error('src/lib/frostBands.generated.js is stale — run: node scripts/gen-frost-bands.mjs')
      process.exit(1)
    }
    console.log('frostBands.generated.js is current')
  } else {
    writeFileSync(OUT_PATH, text)
    console.log(`wrote ${OUT_PATH} (${Object.keys(loadFrostClass().BAND_BY_SLUG).length} slugs)`)
  }
}
