--   the last day of a short month exactly as the engine's writer does.
--   WHY "EITHER MATRIX": a row may have been written before release 1a or under it, and nothing on
--   the row says which. So a date or a missing date that EITHER engine could have produced is
--   attributed to the engine (table, or none), and only what NEITHER could have produced is
--   attributed to the cook (typed). The only cells where the two answers differ are the eleven 1a
--   fridge cells, and no fridge place existed on prod when this was written.
--
-- THE MATRICES ARE FROZEN LITERALS, NEVER THE LIVE ENGINE (05 §6, review3). B's Lambda carries the
--   1b..4 engine, whose cells differ; importing it would silently compare against the wrong table.
--   * before_1a — the engine as shipped before release 1a: BEFORE_1A in
