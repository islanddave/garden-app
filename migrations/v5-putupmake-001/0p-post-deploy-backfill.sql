--   ⚠ If release 1a's AFTER_1A changes before promote A ships, re-freeze after_1a from the SHIPPED
--   commit before this file's first apply. The self-check below (section 1) refuses a matrix pair that
--   does not differ in exactly those eleven cells.
--   Columns, in the literal's order: deep_freezer, fridge_freezer, fridge, pantry, cold_storage, other,
