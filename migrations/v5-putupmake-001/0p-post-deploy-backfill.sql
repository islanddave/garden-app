-- One row per (matrix, method, kind); months NULL = no figure.
CREATE TEMP VIEW putupmake_frozen_cell AS
  SELECT f.matrix, f.method, k.kind, k.months
    FROM putupmake_frozen_matrix f
   CROSS JOIN LATERAL (VALUES ('deep_freezer', f.deep_freezer), ('fridge_freezer', f.fridge_freezer),
                              ('fridge', f.fridge), ('pantry', f.pantry),
                              ('cold_storage', f.cold_storage), ('other', f.other),
                              ('unrecorded', f.unrecorded)) AS k(kind, months);

-- Self-check, so a transcription slip in either literal is loud: both matrices cover exactly the
-- methods the live method CHECK admits, and they differ in exactly the eleven disclosed fridge cells,
-- each a figure before 1a and no date after it.
DO $$
DECLARE
  v_diff   text;
  v_live   text;
  v_frozen text;
BEGIN
  SELECT string_agg(m, ',' ORDER BY m COLLATE "C") INTO v_live
    FROM (SELECT DISTINCT (regexp_matches(pg_get_constraintdef(c.oid), '''([a-z_]+)''', 'g'))[1] AS m
            FROM pg_constraint c
            JOIN pg_class t ON t.oid = c.conrelid
            JOIN pg_namespace n ON n.oid = t.relnamespace
           WHERE n.nspname = 'public' AND t.relname = 'preservation_log'
             AND c.conname = 'chk_preservation_log_method') s;
  FOR v_frozen IN
    SELECT string_agg(method, ',' ORDER BY method COLLATE "C") FROM putupmake_frozen_matrix GROUP BY matrix
  LOOP
    IF v_frozen IS DISTINCT FROM v_live THEN
      RAISE EXCEPTION 'v5-putupmake-001 0p refused: a frozen matrix covers methods [%], the live method CHECK admits [%]', v_frozen, v_live;
    END IF;
  END LOOP;

  SELECT string_agg(b.method || '/' || b.kind || ':' || COALESCE(b.months::text, '-') || '>'
                    || COALESCE(a.months::text, '-'), ',' ORDER BY b.method COLLATE "C", b.kind COLLATE "C") INTO v_diff
    FROM putupmake_frozen_cell b
    JOIN putupmake_frozen_cell a
      ON a.matrix = 'after_1a' AND a.method = b.method AND a.kind = b.kind
   WHERE b.matrix = 'before_1a' AND a.months IS DISTINCT FROM b.months;
  IF v_diff IS DISTINCT FROM
       'blanch_freeze/fridge:10>-,can_pressure/fridge:12>-,can_water_bath/fridge:12>-,'
       'cure_store/fridge:3>-,dehydrate/fridge:4>-,jam_preserve/fridge:12>-,passata/fridge:12>-,'
       'pesto/fridge:10>-,powder/fridge:4>-,roast_freeze/fridge:10>-,whole_freeze/fridge:10>-' THEN
    RAISE EXCEPTION 'v5-putupmake-001 0p refused: the frozen matrices differ in [%], not in exactly the eleven disclosed 1a fridge cells', v_diff;
  END IF;
END $$;

-- ── 2. The backfill ──────────────────────────────────────────────────────────────────────────────
WITH target AS (
  SELECT p.id, p.method, p.preserved_at, p.use_by_target,
         COALESCE(sl.kind, 'unrecorded') AS kind
    FROM public.preservation_log p
    LEFT JOIN public.storage_location sl ON sl.id = p.storage_location_id
   WHERE p.use_by_basis IS NULL
), decided AS (
  SELECT t.id,
         CASE
           WHEN t.use_by_target IS NULL THEN
             CASE WHEN EXISTS (SELECT 1 FROM putupmake_frozen_cell c
                                WHERE c.method = t.method AND c.kind = t.kind AND c.months IS NULL)
                       OR NOT EXISTS (SELECT 1 FROM putupmake_frozen_cell c
                                       WHERE c.method = t.method AND c.kind = t.kind)
                  THEN 'none'
                  ELSE 'typed'
             END
           WHEN EXISTS (SELECT 1 FROM putupmake_frozen_cell c
                         WHERE c.method = t.method AND c.kind = t.kind AND c.months IS NOT NULL
                           AND (t.preserved_at + make_interval(months => c.months))::date
                               = t.use_by_target)
             THEN CASE WHEN t.method = 'candy' THEN 'house' ELSE 'table' END
           ELSE 'typed'
         END AS basis
    FROM target t
)
UPDATE public.preservation_log p
   SET use_by_basis = d.basis
  FROM decided d
 WHERE p.id = d.id
   AND p.use_by_basis IS NULL;

-- What the backfill decided, for the operator's log (whole table, soft-deleted rows included).
SELECT use_by_basis, (use_by_target IS NOT NULL) AS dated, count(*) AS jars
  FROM public.preservation_log
 GROUP BY 1, 2
 ORDER BY 1, 2;

