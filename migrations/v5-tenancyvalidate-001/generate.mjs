#!/usr/bin/env node
// generate.mjs — writes this directory's 25 per-key SQL files (V5-SPACETENANCYKEY-001, multi-space plan V204 step
// 2.3). The table list, its order, the env fingerprints and step 2.1's stamps come from
// ../v5-tenancykey-001/owner-classes.json, read through that directory's generate.mjs, so file NN here validates
// exactly the key that file NN there made. validate.test.js holds every file equal to what this renders, and the
// marked VALUES blocks in gates.yml and 0r-rollback.sql equal to valuesRows().
//
//   node migrations/v5-tenancyvalidate-001/generate.mjs           check: exit 1 naming each file that differs
//   node migrations/v5-tenancyvalidate-001/generate.mjs --write   rewrite the 25 files
//   node migrations/v5-tenancyvalidate-001/generate.mjs --values  print the rows for the marked VALUES blocks
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { loadOwnerClasses, stampOf as keyStampOf, fileOf as keyFileOf, fkName } from '../v5-tenancykey-001/generate.mjs'

export const DIR = dirname(fileURLToPath(import.meta.url))
export const KEY_DIR = join(DIR, '..', 'v5-tenancykey-001')
// The release this step ships in. The session renames the stamps if it moves: edit this, `--write`, the VALUES
// blocks (`--values`) and scripts/phase7-gate.json G1 "2.3".
export const STAMP_PREFIX = '5.3.14-tenancyvalidate-001-'
export const VALUES_BEGIN = '-- BEGIN tenancyvalidate keys'
export const VALUES_END = '-- END tenancyvalidate keys'

const lit = (v) => `'${String(v).replace(/'/g, "''")}'`
const pad = (n) => String(n).padStart(2, '0')
const slug = (t) => t.table.replace(/_/g, '-')

export { loadOwnerClasses, keyStampOf, keyFileOf, fkName }
export const stampOf = (t) => `${STAMP_PREFIX}${slug(t)}`
export const fileOf = (t) => `${pad(t.n)}-${slug(t)}.sql`

// The comment step 2.1 put on each key (its files 01-25), which 0r-rollback.sql writes back after it re-adds the
// key NOT VALID. validate.test.js holds it equal to the text in each 2.1 file.
export const keyComment = (t) => `V5-SPACETENANCYKEY-001 (v5-tenancykey-001 ${pad(t.n)}, step 2.1). A row's Space is a row of public.spaces. RESTRICT: a Space with rows here cannot be deleted. NOT VALID until step 2.3.`
export const validatedComment = (t) => `V5-SPACETENANCYKEY-001 (v5-tenancykey-001 ${pad(t.n)}, step 2.1; validated by v5-tenancyvalidate-001 ${pad(t.n)}, step 2.3). A row's Space is a row of public.spaces. RESTRICT: a Space with rows here cannot be deleted. Validated after an all-row sweep (soft-deleted rows included).`

// The key in 2.1's shape: <table>_workspace_id_fkey, workspace_id alone -> public.spaces(id), ON DELETE RESTRICT.
const keyLookup = (t) => `SELECT k.convalidated
    FROM pg_constraint k
    JOIN pg_class c ON c.oid = k.conrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    JOIN pg_attribute a ON a.attrelid = k.conrelid AND a.attnum = k.conkey[1]
    JOIN pg_class f ON f.oid = k.confrelid
    JOIN pg_namespace fn ON fn.oid = f.relnamespace
    JOIN pg_attribute fa ON fa.attrelid = k.confrelid AND fa.attnum = k.confkey[1]
   WHERE n.nspname = 'public' AND c.relname = ${lit(t.table)} AND k.conname = ${lit(fkName(t))} AND k.contype = 'f'
     AND cardinality(k.conkey) = 1 AND a.attname = 'workspace_id'
     AND cardinality(k.confkey) = 1 AND fn.nspname = 'public' AND f.relname = 'spaces' AND fa.attname = 'id'
     AND k.confdeltype = 'r'`

function file(oc, t, total) {
  const tag = `${pad(t.n)} (${t.table})`
  const stamp = stampOf(t)
  const keyStamp = keyStampOf(oc, t)
  const key = fkName(t)
  const f = oc.fingerprint
  return `-- ${fileOf(t)}
-- V5-SPACETENANCYKEY-001, multi-space step 2.3 (plan V204 §3 row 2.3, §3.0). File ${pad(t.n)} of ${total}.
-- Validates ${key}, which v5-tenancykey-001 file ${pad(t.n)} (${keyFileOf(t)}) added NOT VALID, after the
--   all-row sweep. Stamp ${stamp}.
-- GENERATED by generate.mjs (table list, order and env fingerprints: v5-tenancykey-001/owner-classes.json). Edit
--   the generator, run \`node generate.mjs --write\`; validate.test.js reds on any difference.
--
-- WHAT, in one transaction:
--   0. LOCK ${t.table} IN SHARE UPDATE EXCLUSIVE MODE and spaces IN ROW SHARE MODE: the two locks VALIDATE takes,
--      taken first so the sweep runs under them. Reads and writes of both tables go on. A write meanwhile is
--      checked by the key itself (a NOT VALID key checks every new or updated row), so no row naming no Space
--      can arrive between the sweep and VALIDATE.
--   1. The guard ($pregate$, read-only: the runner's --dry-run runs this block alone): the env and the database's
--      fingerprint; v5-tenancykey-001 file ${pad(t.n)} applied (stamp ${keyStamp}); the key there in 2.1's shape
--      (workspace_id alone -> public.spaces(id), ON DELETE RESTRICT) and NOT VALID; then THE ALL-ROW SWEEP, every
--      row, no deleted_at filter (Migration Authoring Rule, L-058: VALIDATE trips on a soft-deleted row exactly as
--      on a live one):
--        a. rows whose workspace_id names no row of public.spaces (VALIDATE would raise 23503 on them);
--        b. rows whose workspace_id IS NULL, counted separately: a MATCH SIMPLE key passes a NULL, so VALIDATE
--           alone would not see them, and a validated key must mean every row names a Space.
--      Either count above 0 refuses, naming both counts and up to five of the values, and changes nothing.
--   2. ALTER TABLE public.${t.table} VALIDATE CONSTRAINT ${key} (timed: a NOTICE gives the milliseconds), then
--      convalidated read back.
--   3. The key's comment says it is validated; the stamp.
-- ENV. psql -v env=prod|staging (scripts/tenancykey-apply.py --dir v5-tenancyvalidate-001 passes it). Without
--   -v env psql cannot parse the set_config line and nothing runs. Any other value, or a database without that
--   env's schema_version fingerprint, refuses.
-- DEPLOYED CODE (the falsifiable test). VALIDATE changes nothing a write meets: the NOT VALID key has checked every
--   INSERT and UPDATE of this table since file ${pad(t.n)} of v5-tenancykey-001. It proves the rows already there.
-- LOCKS. SHARE UPDATE EXCLUSIVE on ${t.table} and ROW SHARE on spaces, to COMMIT; two scans of ${t.table} (the
--   sweep, then VALIDATE's own). lock_timeout 5s: a wait fails fast (55P03) having changed nothing. The runner
--   refuses at :58-:02 and 07:00-08:00 UTC.
-- RE-RUN. With the stamp present nothing changes. A validated key without the stamp refuses: something other than
--   this file validated it.
-- ROLLBACK: 0r-rollback.sql. A validated key cannot be un-validated in place: the rollback drops it and adds it
--   again NOT VALID, with 2.1's comment.

BEGIN;

SET LOCAL lock_timeout = '5s';
SELECT set_config('tenancyvalidate.env', :'env', true) AS env \\gset tv_

LOCK TABLE public.${t.table} IN SHARE UPDATE EXCLUSIVE MODE;
LOCK TABLE public.spaces IN ROW SHARE MODE;

-- ── 1. The guard and the all-row sweep (read-only). ──────────────────────────────────────────────────────
DO $pregate$
DECLARE
  v_env text := current_setting('tenancyvalidate.env', true);
  v_valid boolean;
  v_orphan bigint;
  v_null bigint;
  v_sample text;
BEGIN
  IF v_env IS NULL OR v_env NOT IN ('prod', 'staging') THEN
    RAISE EXCEPTION 'v5-tenancyvalidate-001 ${tag} refused, nothing changed: env is %, not prod or staging.', coalesce(quote_literal(v_env), 'unset')
      USING HINT = 'Run it with psql -v env=prod or -v env=staging (scripts/tenancykey-apply.py --dir v5-tenancyvalidate-001 does).';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.schema_version
                  WHERE version = CASE v_env WHEN 'prod' THEN ${lit(f.prod.present)} ELSE ${lit(f.staging.present)} END)
     OR EXISTS (SELECT 1 FROM public.schema_version
                 WHERE version = CASE v_env WHEN 'prod' THEN ${lit(f.prod.absent)} ELSE ${lit(f.staging.absent)} END) THEN
    RAISE EXCEPTION 'v5-tenancyvalidate-001 ${tag} refused, nothing changed: this database does not carry the % fingerprint (v5-tenancykey-001/owner-classes.json "fingerprint").', v_env
      USING HINT = 'The -v env value names the other database. Check which URL this is before anything else.';
  END IF;
  IF EXISTS (SELECT 1 FROM public.schema_version WHERE version = ${lit(stamp)}) THEN
    RAISE NOTICE 'v5-tenancyvalidate-001 ${tag}: stamp ${stamp} present; nothing to check.';
    RETURN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.schema_version WHERE version = ${lit(keyStamp)}) THEN
    RAISE EXCEPTION 'v5-tenancyvalidate-001 ${tag} refused, nothing changed: v5-tenancykey-001 file ${pad(t.n)} has not run (stamp ${keyStamp} absent).'
      USING HINT = 'Step 2.1 adds the key this file validates. Apply it first.';
  END IF;
  ${keyLookup(t)}
    INTO v_valid;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'v5-tenancyvalidate-001 ${tag} refused, nothing changed: ${key} is not on public.${t.table} in the shape v5-tenancykey-001 made (workspace_id alone -> public.spaces(id), ON DELETE RESTRICT).'
      USING HINT = 'Something changed the key since step 2.1. Find what, before anything else.';
  END IF;
  IF v_valid THEN
    RAISE EXCEPTION 'v5-tenancyvalidate-001 ${tag} refused, nothing changed: ${key} is already validated but stamp ${stamp} is absent.'
      USING HINT = 'Something other than this file validated it. Find what, before anything else.';
  END IF;

  -- The all-row sweep: every row, soft-deleted ones included.
  SELECT count(*) FILTER (WHERE t.workspace_id IS NOT NULL
                            AND NOT EXISTS (SELECT 1 FROM public.spaces s WHERE s.id = t.workspace_id)),
         count(*) FILTER (WHERE t.workspace_id IS NULL)
    INTO v_orphan, v_null
    FROM public.${t.table} t;
  RAISE NOTICE 'v5-tenancyvalidate-001 ${tag} sweep, every row (deleted included): % row(s) name no Space, % row(s) NULL.', v_orphan, v_null;
  IF v_orphan > 0 OR v_null > 0 THEN
    SELECT string_agg(format('%s: %s row(s)', coalesce(x.workspace_id::text, 'NULL'), x.n), ', ' ORDER BY x.workspace_id::text)
      INTO v_sample
      FROM (SELECT t.workspace_id, count(*) AS n
              FROM public.${t.table} t
             WHERE t.workspace_id IS NULL
                OR NOT EXISTS (SELECT 1 FROM public.spaces s WHERE s.id = t.workspace_id)
             GROUP BY t.workspace_id
             ORDER BY t.workspace_id::text NULLS FIRST
             LIMIT 5) x;
    RAISE EXCEPTION 'v5-tenancyvalidate-001 ${tag} refused, nothing changed: the all-row sweep found % row(s) naming no Space and % row(s) with a NULL workspace_id (%).', v_orphan, v_null, v_sample
      USING HINT = 'Triage each row (L-058): a row that names no Space is either repaired to its Space or, if it is test debris, hard-deleted with Dave''s OK. Never filter the sweep.';
  END IF;
END $pregate$;

-- ── 2. VALIDATE, once. ───────────────────────────────────────────────────────────────────────────────────
DO $ddl$
DECLARE
  v_t0 timestamptz;
  v_valid boolean;
BEGIN
  IF EXISTS (SELECT 1 FROM public.schema_version WHERE version = ${lit(stamp)}) THEN
    RAISE NOTICE 'v5-tenancyvalidate-001 ${tag}: already applied; nothing changed.';
    RETURN;
  END IF;

  v_t0 := clock_timestamp();
  ALTER TABLE public.${t.table} VALIDATE CONSTRAINT ${key};
  RAISE NOTICE 'v5-tenancyvalidate-001 ${tag}: VALIDATE CONSTRAINT ${key} took % ms.',
    round((extract(epoch FROM clock_timestamp() - v_t0) * 1000)::numeric, 1);

  ${keyLookup(t)}
    INTO v_valid;
  IF v_valid IS NOT TRUE THEN
    RAISE EXCEPTION 'v5-tenancyvalidate-001 ${tag}: ${key} is not validated after VALIDATE; rolled back.';
  END IF;
END $ddl$;

-- ── 3. Comment and the stamp. ────────────────────────────────────────────────────────────────────────────
COMMENT ON CONSTRAINT ${key} ON public.${t.table} IS
  ${lit(validatedComment(t))};

INSERT INTO public.schema_version (version, description)
VALUES (${lit(stamp)},
        'TENANCYVALIDATE ${t.table}: V5-SPACETENANCYKEY-001 (multi-space step 2.3, file ${pad(t.n)} of ${total}). '
        'All-row sweep (no deleted_at filter) found 0 rows naming no Space and 0 NULL, then VALIDATE CONSTRAINT '
        '${key}. Section '
        || current_setting('tenancyvalidate.env') || '.')
ON CONFLICT (version) DO NOTHING;

COMMIT;
`
}

export function render(oc = loadOwnerClasses(KEY_DIR)) {
  const total = oc.tables.length
  return oc.tables.map((t) => ({ name: fileOf(t), text: file(oc, t, total) }))
}

// (n, relname, conname, key_stamp, stamp), one row per key in file order, for the marked VALUES blocks.
export function valuesRows(oc = loadOwnerClasses(KEY_DIR)) {
  const rows = oc.tables.map((t) => `(${t.n}, ${[t.table, fkName(t), keyStampOf(oc, t), stampOf(t)].map(lit).join(', ')})`)
  return rows.map((r, i) => r + (i < rows.length - 1 ? ',' : ''))
}

// Every marked VALUES block in a file's text, each as its trimmed, non-empty lines.
export function valuesBlocksIn(text) {
  const blocks = []
  const lines = text.split('\n')
  for (let i = 0; i < lines.length; i++) {
    if (lines[i].trim() !== VALUES_BEGIN) continue
    const rows = []
    let j = i + 1
    for (; j < lines.length && lines[j].trim() !== VALUES_END; j++) if (lines[j].trim()) rows.push(lines[j].trim())
    if (j === lines.length) throw new Error(`unterminated ${VALUES_BEGIN} at line ${i + 1}`)
    blocks.push({ line: i + 1, rows })
    i = j
  }
  return blocks
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const argv = process.argv.slice(2)
  if (argv.includes('--values')) {
    console.log(valuesRows().join('\n'))
  } else {
    let bad = 0
    for (const { name, text } of render()) {
      const p = join(DIR, name)
      if (argv.includes('--write')) writeFileSync(p, text)
      else if (!existsSync(p) || readFileSync(p, 'utf8') !== text) { console.error(`differs from the generator: ${name}`); bad++ }
    }
    if (bad) process.exit(1)
  }
}
